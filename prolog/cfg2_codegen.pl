%% cfg2_codegen.pl
%% Code generation and export for CFG Converter 2.
%%
%% Generates Prolog module source text from the result structure.

:- module(cfg2_codegen,
    [
        generate_module2/4,
        export_cfg2/3,
        export_cfg2/4,
        result_to_prolog_text/2,
        result_to_cfg_text/2,
        result_to_json_text/2
    ]).

:- use_module(library(lists)).
:- use_module(cfg2_cfg).
:- use_module(cfg2_dcg).

%% generate_module2(+Name, +IR, +EvidenceDB, -ModuleText) is det.
%  Generates a complete SWI-Prolog module from the IR and evidence.
generate_module2(Name, _IR, EvidenceDB, ModuleText) :-
    format(atom(ModuleText),
           ':- module(~w, []).~n~n% Generated by CFG Converter 2~n% Evidence count: ~w~n',
           [Name, length(EvidenceDB)]).

%% export_cfg2(+Result, +Format, +Path) is det.
export_cfg2(Result, Format, Path) :-
    export_cfg2(Result, Format, Path, []).

%% export_cfg2(+Result, +Format, +Path, +Options) is det.
export_cfg2(Result, prolog, Path, Options) :-
    result_to_prolog_text(Result, Text),
    safe_write_file(Path, Text, Options).
export_cfg2(Result, cfg, Path, Options) :-
    result_to_cfg_text(Result, Text),
    safe_write_file(Path, Text, Options).
export_cfg2(Result, json, Path, Options) :-
    result_to_json_text(Result, Text),
    safe_write_file(Path, Text, Options).
export_cfg2(_Result, Format, _Path, _Options) :-
    throw(error(unsupported_export_format(Format), export_cfg2/4)).

%% result_to_prolog_text(+Result, -Text) is det.
result_to_prolog_text(Result, Text) :-
    Result = result(project(Name), department(Dept), _, _, _,
                    _, cfg(CFGRules, _), dcg(DCGClauses), _,
                    _, _, module(ModText), _, _),
    cfg_to_text(CFGRules, CFGText),
    dcg_to_prolog(DCGClauses, DCGText),
    format(atom(Text),
           '% CFG Converter 2 output\n% Project: ~w\n% Department: ~w\n\n~w\n\n% CFG:\n% ~w\n\n% DCG:\n~w\n',
           [Name, Dept, ModText, CFGText, DCGText]).

%% result_to_cfg_text(+Result, -Text) is det.
result_to_cfg_text(Result, Text) :-
    (   Result = result(_, _, _, _, _, _, cfg(_, CFGText), _, _, _, _, _, _, _)
    ->  Text = CFGText
    ;   Text = '% No CFG generated'
    ).

%% result_to_json_text(+Result, -Text) is det.
result_to_json_text(Result, Text) :-
    term_to_atom(Result, Atom),
    format(atom(Text), '{"result": "~w"}', [Atom]).

%% safe_write_file(+Path, +Text, +Options) is det.
%  Writes text to a file, checking for path traversal.
safe_write_file(Path, Text, Options) :-
    (   atom(Path),
        \+ sub_atom(Path, _, _, _, '..'),
        (   member(export_dir(Dir), Options)
        ->  atom_concat(Dir, _, Path)
        ;   true
        )
    ->  setup_call_cleanup(
            open(Path, write, Stream),
            write(Stream, Text),
            close(Stream)
        )
    ;   throw(error(unsafe_path(Path), safe_write_file/3))
    ).
