%% cfg2_codegen.pl
%% Code generation and export for CFG Converter 2.
%%
%% Generates Prolog module source text from the result structure.

:- module(cfg2_codegen,
    [
        generate_module2/4,
        export_cfg2/3,
        export_cfg2/4,
        result_to_prolog_text/2,
        result_to_cfg_text/2,
        result_to_json_text/2
    ]).

:- use_module(library(lists)).
:- use_module(cfg2_cfg).
:- use_module(cfg2_dcg).

%% generate_module2(+Name, +IR, +EvidenceDB, -ModuleText) is det.
%  Generates a complete SWI-Prolog module from the IR and evidence: the DCG
%  rules, a top//1 rule that parses any root rule, a word rule for each
%  nonterminal used but not defined, and the evidence facts the rules'
%  constraints check (cfg2_evidence_valid/1, cfg2_evidence_measurement/3).
%  (Before, the module held only comments, and its evidence count was
%  written as the expression length([...]).)
generate_module2(Name, IR, EvidenceDB, ModuleText) :-
    length(EvidenceDB, Count),
    generate_dcg2(Name, IR, EvidenceDB, DCGClauses),
    dcg_to_prolog(DCGClauses, RulesText),
    module_entry_rules(DCGClauses, EntryText),
    evidence_fact_text(EvidenceDB, FactsText),
    format(atom(ModuleText),
           ':- module(~w, [parse/2, parse/4]).~n~n% Generated by CFG Converter 2~n% Evidence count: ~w~n~n:- discontiguous cfg2_evidence_valid/1, cfg2_evidence_measurement/3.~n~n%% Evidence~n~w~n~n%% Grammar~n~w~n~n%% Entry and word rules~n~w~n~nparse(Tokens, Tree) :- phrase(top(Tree, _, _), Tokens).~nparse(Tokens, Tree, Sem, EvState) :- phrase(top(Tree, Sem, EvState), Tokens).~n',
           [Name, Count, FactsText, RulesText, EntryText]).

module_entry_rules(DCGClauses, Text) :-
    findall(H, member(dcg_clause(head(H, _), _), DCGClauses), Hs0), sort(Hs0, Heads),
    findall(N, ( member(dcg_clause(_, body(Goals, _, _)), DCGClauses),
                 member(nonterminal_goal(N, _), Goals) ), Ns0), sort(Ns0, Used),
    subtract(Heads, Used, Roots0),
    ( Roots0 == [] -> Roots = Heads ; Roots = Roots0 ),
    findall(T, ( member(R, Roots), format(atom(T), 'top(T, S, E) --> ~w(T, S, E).', [R]) ), Tops0),
    ( Tops0 == [] -> Tops = ['top(tree(empty, []), sem([]), evstate([])) --> [].'] ; Tops = Tops0 ),
    subtract(Used, Heads, Words),
    findall(T, ( member(W, Words), format(atom(T), '~q(tree(~q, []), sem([]), evstate([])) --> [~q].', [W, W, W]) ), WordRules),
    Helper = 'nonterminal_goal(N, [T, S, E]) --> { G =.. [N, T, S, E] }, call_dcg_goal(G).\ncall_dcg_goal(G, S0, S) :- call(G, S0, S).',
    append([Tops, WordRules, [Helper]], All),
    atomic_list_concat(All, '\n', Text).

evidence_fact_text(EvidenceDB, Text) :-
    findall(L, ( member(E, EvidenceDB), evidence_fact(E, L) ), Ls),
    ( Ls == [] -> Text = '% (no evidence)' ; atomic_list_concat(Ls, '\n', Text) ).

evidence_fact(E, L) :-
    compound(E), functor(E, evidence, _), arg(1, E, Id),
    (   arg(4, E, Var), arg(5, E, Val)
    ->  format(atom(L), 'cfg2_evidence_valid(~q).\ncfg2_evidence_measurement(~q, ~q, ~q).', [Id, Id, Var, Val])
    ;   format(atom(L), 'cfg2_evidence_valid(~q).', [Id])
    ).

%% export_cfg2(+Result, +Format, +Path) is det.
export_cfg2(Result, Format, Path) :-
    export_cfg2(Result, Format, Path, []).

%% export_cfg2(+Result, +Format, +Path, +Options) is det.
export_cfg2(Result, prolog, Path, Options) :-
    result_to_prolog_text(Result, Text),
    safe_write_file(Path, Text, Options).
export_cfg2(Result, cfg, Path, Options) :-
    result_to_cfg_text(Result, Text),
    safe_write_file(Path, Text, Options).
export_cfg2(Result, json, Path, Options) :-
    result_to_json_text(Result, Text),
    safe_write_file(Path, Text, Options).
export_cfg2(_Result, Format, _Path, _Options) :-
    throw(error(unsupported_export_format(Format), export_cfg2/4)).

%% result_to_prolog_text(+Result, -Text) is det.
result_to_prolog_text(Result, Text) :-
    Result = result(project(Name), department(Dept), _, _, _,
                    _, cfg(CFGRules, _), dcg(DCGClauses), _,
                    _, _, module(ModText), _, _),
    cfg_to_text(CFGRules, CFGText),
    dcg_to_prolog(DCGClauses, DCGText),
    % the module already holds the DCG rules, so they are not written twice
    ( sub_atom(ModText, _, _, _, '%% Grammar') -> DCGPart = '% (in the module above)' ; DCGPart = DCGText ),
    format(atom(Text),
           '% CFG Converter 2 output\n% Project: ~w\n% Department: ~w\n\n~w\n\n% CFG:\n% ~w\n\n% DCG:\n~w\n',
           [Name, Dept, ModText, CFGText, DCGPart]).

%% result_to_cfg_text(+Result, -Text) is det.
result_to_cfg_text(Result, Text) :-
    (   Result = result(_, _, _, _, _, _, cfg(_, CFGText), _, _, _, _, _, _, _)
    ->  Text = CFGText
    ;   Text = '% No CFG generated'
    ).

%% result_to_json_text(+Result, -Text) is det.
result_to_json_text(Result, Text) :-
    term_to_atom(Result, Atom),
    format(atom(Text), '{"result": "~w"}', [Atom]).

%% safe_write_file(+Path, +Text, +Options) is det.
%  Writes text to a file, checking for path traversal.
safe_write_file(Path, Text, Options) :-
    (   atom(Path),
        \+ sub_atom(Path, _, _, _, '..'),
        (   member(export_dir(Dir), Options)
        ->  atom_concat(Dir, _, Path)
        ;   true
        )
    ->  setup_call_cleanup(
            open(Path, write, Stream),
            write(Stream, Text),
            close(Stream)
        )
    ;   throw(error(unsafe_path(Path), safe_write_file/3))
    ).
