%% ideacfg_codegen.pl
%% Code generation: assembles complete Prolog modules from IR.
:- module(ideacfg_codegen,
    [
        generate_module/3,
        generate_operation_predicates/2,
        generate_test_suite/3,
        generated_rule/5,
        generated_operation/4
    ]).

:- use_module(ideacfg_ir).
:- use_module(ideacfg_cfg).
:- use_module(ideacfg_dcg).
:- use_module(ideacfg_operations).
:- use_module(ideacfg_diagnostics).
:- use_module(library(lists)).

%% generate_module(+IdeaName, +IR, -ModuleText) is det.
%  Generates a complete Prolog module as an atom.
generate_module(IdeaName, IR, ModuleText) :-
    must_be(atom, IdeaName),
    format(atom(ModName), 'idea_~w', [IdeaName]),
    generate_dcg(IdeaName, IR, DCGClauses),
    dcg_to_prolog_text(DCGClauses, DCGText),
    generate_operation_predicates(IR, OpsText),
    format(atom(ModuleText),
':- module(~w,\n    [\n        idea_parse/3,\n        idea_generate/2,\n        idea_compute/3,\n        idea_validate/2,\n        idea_explain/2\n    ]).\n\n:- use_module(library(lists)).\n\n%% Generated DCG rules\n~w\n\n%% Generated operation predicates\n~w\n\n%% idea_parse(+IdeaName, +Tokens, -Tree) is semidet.\nidea_parse(~w, Tokens, Tree) :-\n    phrase(top(Tree), Tokens).\n\n%% idea_generate(+IdeaName, -Tokens) is nondet.\nidea_generate(~w, Tokens) :-\n    phrase(top(_), Tokens).\n\n%% idea_compute(+IdeaName, +Bindings, -Results) is det.\nidea_compute(~w, Bindings, Results) :-\n    maplist([K-V, K-V]>>true, Bindings, Results).\n\n%% idea_validate(+IdeaName, +Tree) is semidet.\nidea_validate(~w, _Tree).\n\n%% idea_explain(+IdeaName, -Explanation) is det.\nidea_explain(~w, explanation(~w, \'Generated by IdeaCFG\')).\n',
[ModName, DCGText, OpsText,
 IdeaName, IdeaName, IdeaName, IdeaName, IdeaName, IdeaName]).

%% generate_operation_predicates(+IR, -Text) is det.
%  Generates Prolog predicate text for all extracted operations.
generate_operation_predicates(IR, Text) :-
    ir_operations(IR, Ops),
    maplist(op_to_prolog, Ops, OpTexts),
    atomic_list_concat(OpTexts, '\n\n', Text).

op_to_prolog(operation(Id, arithmetic, Inputs, _Output, direct, _Props, Src), Text) :-
    sanitise_pred_name(Id, PredName),
    length(Inputs, NIn),
    findall(V, (between(1, NIn, I), atomic_list_concat([v, I], V)), ArgNames),
    atomic_list_concat(ArgNames, ', ', ArgsText),
    (   NIn > 0
    ->  format(atom(ArgsWithResult), '~w, Result', [ArgsText])
    ;   ArgsWithResult = 'Result'
    ),
    format(atom(CheckText), '    % Source: ~w\n', [Src]),
    format(atom(Text),
        '%% ~w(~w) is det.\n~w~w(~w) :-\n    maplist(must_be(number), [~w]),\n    Result = unresolved.\n',
        [PredName, ArgsWithResult, CheckText, PredName, ArgsWithResult, ArgsText]).
op_to_prolog(operation(Id, _Class, _In, _Out, _Mode, _Props, Src), Text) :-
    sanitise_pred_name(Id, PredName),
    format(atom(Text), '%% ~w/1 is det.\n% Source: ~w\n~w(_) :- true.\n', [PredName, Src, PredName]).

%% generate_test_suite(+IdeaName, +IR, -TestText) is det.
%  Generates a plunit test file.
generate_test_suite(IdeaName, _IR, TestText) :-
    must_be(atom, IdeaName),
    format(atom(TestText),
':- use_module(library(plunit)).\n:- use_module(idea_~w).\n\n:- begin_tests(~w).\n\ntest(module_loads) :-\n    true.\n\ntest(idea_compute_stub) :-\n    idea_compute(~w, [], []).\n\n:- end_tests(~w).\n',
    [IdeaName, IdeaName, IdeaName, IdeaName]).

%% generated_rule(+RuleId, +IdeaName, +Rhs, +Trace, -Term) is det.
%  Creates a generated_rule traceability term.
generated_rule(RuleId, IdeaName, Rhs, Trace, generated_rule(RuleId, IdeaName, Rhs, Trace)).

%% generated_operation(+OpId, +PredName, +Class, -Term) is det.
generated_operation(OpId, PredName, Class, generated_operation(OpId, PredName, Class, [])).

sanitise_pred_name(Id, Clean) :-
    atom_string(Id, Str),
    re_replace("[^a-z0-9_]"/g, "_", Str, Cleaned),
    atom_string(Clean, Cleaned).
